esp_err_t sendCmd(uint8_t cmd, const uint8_t *params, size_t len) {
    spi_transaction_ext_t ext = {};
    ext.base.flags = SPI_TRANS_VARIABLE_CMD | SPI_TRANS_VARIABLE_ADDR;
    ext.base.cmd = QSPI_OPCODE_WRITE_CMD;
    ext.base.addr = static_cast<uint32_t>(cmd) << 8;
    ext.base.length = len * 8;
    ext.base.tx_buffer = (len > 0) ? params : nullptr;
    ext.command_bits = 8;
    ext.address_bits = 24;
    return spi_device_polling_transmit(s_spi, &ext.base);
}

esp_err_t sendColorStrip(const uint8_t *data, size_t bytes) {
    spi_transaction_ext_t ext = {};
    ext.base.flags = SPI_TRANS_VARIABLE_CMD | SPI_TRANS_VARIABLE_ADDR | SPI_TRANS_MODE_QIO;
    ext.command_bits = 8;
    ext.address_bits = 24;
    ext.base.cmd = QSPI_OPCODE_WRITE_COLOR;
    ext.base.addr = static_cast<uint32_t>(CMD_RAMWR) << 8;
    ext.base.length = bytes * 8;
    ext.base.tx_buffer = data;
    return spi_device_polling_transmit(s_spi, &ext.base);
}

void lvglFlushCb(lv_disp_drv_t *drv, const lv_area_t *area, lv_color_t *color_p) {
    DisplaySpd2010::drawBitmap(area->x1, area->y1, area->x2, area->y2,
                               reinterpret_cast<const uint16_t *>(color_p));
    lv_disp_flush_ready(drv);
}

// SPD2010 QSPI pixel unpacker requires horizontal windows aligned to 4-pixel boundaries.
void lvglRounderCb(lv_disp_drv_t *drv, lv_area_t *area) {
    (void)drv;
    area->x1 &= ~3;
    area->x2 |= 3;
    if (area->x2 >= LCD_WIDTH) {
        area->x2 = LCD_WIDTH - 1;
    }
}

